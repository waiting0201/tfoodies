const FALLBACK = '信用卡授權未通過，請確認卡片資料後再試一次，或改用其他付款方式。'

/** 把財金 errcode 翻成顧客看得懂的說明；未知或未帶代碼一律回通用訊息。 */
export function fiscErrorMessage(errCode?: string | null): string {
  if (!errCode) return FALLBACK
  // 財金 errcode 固定 2 位，但保險起見補零比對（"5" → "05"）。
  const key = String(errCode).trim().padStart(2, '0')
  return FISC_ERROR_MESSAGES[key] ?? FALLBACK
}
